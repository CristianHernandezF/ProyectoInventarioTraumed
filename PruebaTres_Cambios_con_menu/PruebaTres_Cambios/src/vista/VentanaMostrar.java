    private void btn_modificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_modificarActionPerformed
        
        int fila=jt_tabla.getSelectedRow();
        // variables del producto
        int id_producto = 0, precio = 0, stock = 0;
        String nombre = null, marca = null, material = null;
        
        // las variables del tornillo
        double medida = 0, diametro = 0, largo = 0;
        int cantidadAgujeros = 0;
        String tipoCabeza = null;

        // bandera para indicar cuando pasa algo malo :(
        boolean datosValidos = true;

        // verifica si esta seleccionando una fila
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto de la tabla.");
            datosValidos = false;
        }

        // Hacemos la validacion de cada una de las columnas
        if (datosValidos) {
            id_producto = validarIntValor(String.valueOf(jt_tabla.getValueAt(fila, 0)), "ID");
            if (id_producto == -1) datosValidos = false;
        }

        if (datosValidos) {
            nombre = validarStringValor(String.valueOf(jt_tabla.getValueAt(fila, 1)), "Nombre");
            if (nombre == null) datosValidos = false;
        }

        if (datosValidos) {
            marca = validarStringValor(String.valueOf(jt_tabla.getValueAt(fila, 2)), "Marca");
            if (marca == null) datosValidos = false;
        }

        if (datosValidos) {
            material = validarStringValor(String.valueOf(jt_tabla.getValueAt(fila, 3)), "Material");
            if (material == null) datosValidos = false;
        }

        if (datosValidos) {
            precio = validarIntValor(String.valueOf(jt_tabla.getValueAt(fila, 5)), "Precio");
            if (precio == -1) datosValidos = false;
        }

        if (datosValidos) {
            stock = validarIntValor(String.valueOf(jt_tabla.getValueAt(fila, 6)), "Stock");
            if (stock == -1) datosValidos = false;
        }

        // Validacion para las placas o tornillos.
        if (datosValidos) {
            
            if (opt_placa.isSelected()) {
                
                medida = validarDoubleValor(String.valueOf(jt_tabla.getValueAt(fila, 7)), "Medida");
                if (medida == -1) datosValidos = false;

                if (datosValidos) {
                    cantidadAgujeros = validarIntValor(String.valueOf(jt_tabla.getValueAt(fila, 8)), "Agujeros");
                    if (cantidadAgujeros == -1) datosValidos = false;
                }

                // Vamos a guardar la placa.
                if (datosValidos) {
                    TipoProducto tipo = new TipoProducto(1, "placa");
                    Placa pla = new Placa(medida, cantidadAgujeros, id_producto, nombre, material, marca, precio, stock, tipo);
                    PlacaDAO plaDAO = new PlacaDAO();
                    

                    boolean exito = plaDAO.modificarPlaca(pla);
                
                    if(exito) 
                        JOptionPane.showMessageDialog(this, "Placa modificada !"); 
                    
                }

            } else if (opt_tornillo.isSelected()) { 

                

                diametro = validarDoubleValor(String.valueOf(jt_tabla.getValueAt(fila, 7)), "Diámetro");
                if (diametro == -1) datosValidos = false;

                if (datosValidos) {
                    largo = validarDoubleValor(String.valueOf(jt_tabla.getValueAt(fila, 8)), "Largo");
                    if (largo == -1) datosValidos = false;
                }

                if (datosValidos) {
                    tipoCabeza = validarStringValor(String.valueOf(jt_tabla.getValueAt(fila, 9)), "Tipo Cabeza");
                    if (tipoCabeza == null) datosValidos = false;
                }

                // Se guarda el Tornillo
                if (datosValidos) {
                    TipoProducto tipo = new TipoProducto(2, "tornillo");
                    Tornillo torni = new Tornillo(diametro, largo, tipoCabeza, id_producto, nombre, material, marca, precio, stock, tipo);
                    TornilloDAO torniDAO = new TornilloDAO();
                    
                    torniDAO.modificarTornillo(torni);
                    JOptionPane.showMessageDialog(this, "Tornillo modificado!");
                }

            } else {
                JOptionPane.showMessageDialog(this, "Seleccione el tipo de producto (Placa/Tornillo) correspondiente a la fila.");
            }
        }
    
                                                   
    }//GEN-LAST:event_btn_modificarActionPerformed

    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
       DefaultTableModel dtm=(DefaultTableModel)jt_tabla.getModel();
       int fila=jt_tabla.getSelectedRow();
       if(opt_placa.isSelected()){ 
            if(fila==-1)
                JOptionPane.showMessageDialog(this, "Debe seleccionar una Placa");
            else
            {
                int id_producto=Integer.parseInt(String.valueOf(jt_tabla.getValueAt(fila, 0)));
                ProductoDAO proDAO=new ProductoDAO();
                proDAO.eliminarProducto(id_producto);
                JOptionPane.showMessageDialog(this, "Placa eliminada");
                dtm.removeRow(fila);
            }
       }else{
           if(fila==-1)
                JOptionPane.showMessageDialog(this, "Debe seleccionar un Tornillo");
            else
            {
                int id_producto=Integer.parseInt(String.valueOf(jt_tabla.getValueAt(fila, 0)));
                ProductoDAO proDAO=new ProductoDAO();
                proDAO.eliminarProducto(id_producto);
                JOptionPane.showMessageDialog(this, "Tornillo eliminado");
                dtm.removeRow(fila);
       
            }
       }    
    }//GEN-LAST:event_btn_eliminarActionPerformed

