    public String validarStringValor(String texto, String nombreCampo) {
        if (texto == null || texto.trim().length() == 0 ){
            JOptionPane.showMessageDialog(this, "El dato de la columna '" + nombreCampo + "' no puede estar vacío.");
            return null; // Error
        }
        return texto.trim();
    }


    

    
    public int validarIntValor(String texto, String nombreCampo) {
        if (texto == null) texto = "";
        
        texto = texto.trim();

        if (!isInteger(texto)) {
            JOptionPane.showMessageDialog(this, "El dato de la columna '" + nombreCampo + "' debe ser un número entero.");
            return -1;
        }
        int valor = Integer.parseInt(texto);
        if (valor < 0 || valor > 30000) {
            JOptionPane.showMessageDialog(this, "el campo '" + nombreCampo + "'debe estar entre un rango de 0 a 30000.");
            return -1;
        }
        return valor;
  
        
    }

   
    public double validarDoubleValor(String texto, String nombreCampo) {
        if (texto == null) texto = "";
        texto = texto.trim();
        
        double valor = 0;
        boolean esDecimal = true;
        try {
            valor = Double.parseDouble(texto);
        } catch (NumberFormatException e) {
            esDecimal = false;
        }

        if (!esDecimal) {
            JOptionPane.showMessageDialog(this, "El dato de la columna '" + nombreCampo + "' debe ser un número decimal.");
            return -1; // Valor dummy
        }
        if (valor < 0 || valor > 50) {
            JOptionPane.showMessageDialog(this, "El dato de la columna '" + nombreCampo + "' tiene que estar en un rango de 0 a 50 ej '12.5'");
            return -1;
        }
        return valor;
    }
    
  
